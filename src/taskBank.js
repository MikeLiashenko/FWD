export function pickFromBank(difficulty, recentTitles) {
  const all = TASK_BANK[difficulty];
  const fresh = all.filter(([title]) => !recentTitles.includes(title));
  const pool = fresh.length ? fresh : all;
  const [title, description] = pool[Math.floor(Math.random() * pool.length)];
  return { title, description };
}
